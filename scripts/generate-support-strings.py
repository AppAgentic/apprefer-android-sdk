#!/usr/bin/env python3
"""Builds the Support chat's Android string resources from the shared translation table
(Localization/support-strings.json, the same file the iOS, Flutter and React Native SDKs use).

Writes apprefer/src/main/res/values[-<qualifier>]/apprefer_support_strings.xml (<string> and
<plurals>, one file per language) and apprefer/src/main/kotlin/com/apprefer/sdk/support/
SupportStringIds.kt (table key -> resource id). Resource names are the key with an
"apprefer_" prefix, dots and camelCase turned into underscores.

    python3 scripts/generate-support-strings.py [path/to/support-strings.json]
"""
import json, os, re, sys
from xml.sax.saxutils import escape as xml_escape

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
source = sys.argv[1] if len(sys.argv) > 1 else os.path.join(root, "Localization", "support-strings.json")
table = json.load(open(source, encoding="utf-8"))
keys = table["keys"]
languages = {"en": {k: v["en"] for k, v in keys.items()}, **table["translations"]}
res_dir = os.path.join(root, "apprefer", "src", "main", "res")
ids_file = os.path.join(root, "apprefer", "src", "main", "kotlin", "com", "apprefer", "sdk", "support", "SupportStringIds.kt")

# Table language -> Android resource qualifier. Hebrew and Indonesian use the legacy codes
# (iw, in) the platform looks up on every API level; Chinese uses BCP 47 script qualifiers.
QUALIFIERS = {
    "en": "", "es-MX": "es-rMX", "pt-BR": "pt-rBR", "pt-PT": "pt-rPT",
    "zh-Hans": "b+zh+Hans", "zh-Hant": "b+zh+Hant", "he": "iw", "id": "in",
}
PLURAL_ORDER = ["zero", "one", "two", "few", "many", "other"]

def resource_name(key):
    snake = re.sub(r"(?<=[a-z0-9])([A-Z])", r"_\1", key).lower().replace(".", "_")
    return "apprefer_" + snake

def android_escape(text):
    """Android string resource escaping: XML, then quotes/backslashes/newlines and a leading @ or ?."""
    s = text.replace("\\", "\\\\").replace("'", "\\'").replace('"', '\\"').replace("\n", "\\n").replace("\t", "\\t")
    s = xml_escape(s)
    if s[:1] in ("@", "?"):
        s = "\\" + s
    return s

names = {k: resource_name(k) for k in keys}
assert len(set(names.values())) == len(names), "two keys map to the same resource name"
for lang, strings in languages.items():
    missing = set(keys) - set(strings)
    assert not missing, f"{lang} is missing {sorted(missing)}"

for lang, strings in sorted(languages.items()):
    qualifier = QUALIFIERS.get(lang, lang)
    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        "<!-- Generated by scripts/generate-support-strings.py from Localization/support-strings.json. Do not edit. -->",
        '<resources xmlns:tools="http://schemas.android.com/tools">',
    ]
    for key in keys:  # table order
        value = strings[key]
        comment = keys[key].get("comment", "").replace("--", "-")
        lines.append(f"    <!-- {key}: {comment} -->")
        if isinstance(value, dict):
            # Every form carries {count}, filled in by the SDK (not %d). The forms are the table's
            # CLDR categories for whole numbers, which can be newer than lint's plural data; a form a
            # device's rules ask for but the table lacks falls back to "other".
            lines.append(f'    <plurals name="{names[key]}" tools:ignore="ImpliedQuantity,MissingQuantity,UnusedQuantity">')
            for category in sorted(value, key=PLURAL_ORDER.index):
                lines.append(f'        <item quantity="{category}">{android_escape(value[category])}</item>')
            lines.append("    </plurals>")
        else:
            lines.append(f'    <string name="{names[key]}">{android_escape(value)}</string>')
    lines.append("</resources>")
    folder = os.path.join(res_dir, "values" + (f"-{qualifier}" if qualifier else ""))
    os.makedirs(folder, exist_ok=True)
    with open(os.path.join(folder, "apprefer_support_strings.xml"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")

plural_keys = [k for k in keys if isinstance(languages["en"][k], dict)]
text_keys = [k for k in keys if k not in plural_keys]
kt = [
    "// Generated by scripts/generate-support-strings.py from Localization/support-strings.json. Do not edit.",
    "package com.apprefer.sdk.support",
    "",
    "import com.apprefer.sdk.R",
    "",
    "/** Support table keys and their Android resources. */",
    "internal object SupportStringIds {",
    "    /** Every language the table has, as table codes (\"pt-BR\", \"zh-Hant\"). */",
    "    val languages: List<String> = listOf(" + ", ".join(f'"{l}"' for l in sorted(languages)) + ")",
    "",
    "    /** Table language -> resource folder qualifier (\"\" is the default folder, English). */",
    "    val qualifiers: Map<String, String> = mapOf(" + ", ".join(f'"{l}" to "{QUALIFIERS.get(l, l)}"' for l in sorted(languages)) + ")",
    "",
    "    val text: Map<String, Int> by lazy {",
    "        mapOf(",
]
kt += [f'            "{k}" to R.string.{names[k]},' for k in text_keys]
kt += [
    "        )",
    "    }",
    "",
    "    val plurals: Map<String, Int> by lazy {",
    "        mapOf(",
]
kt += [f'            "{k}" to R.plurals.{names[k]},' for k in plural_keys]
kt += [
    "        )",
    "    }",
    "}",
    "",
]
with open(ids_file, "w", encoding="utf-8") as f:
    f.write("\n".join(kt))
print(f"{len(languages)} languages, {len(keys)} keys ({len(plural_keys)} plural) -> {res_dir}")
